#!/usr/bin/env bash
# 自托管数据库备份：public + auth 全量 custom dump，原子落盘 + 可读性校验 + 保留期清理。
#
# 用法：
#   BACKUP_DB_URL='postgresql://postgres@127.0.0.1:5432/postgres' \
#     bash scripts/migrate/db-backup.sh
#   OUT_DIR=/opt/liorvix-backups RETENTION_DAYS=14 bash scripts/migrate/db-backup.sh
#
# 设计：
#   * 与 dump-from-cloud.sh 相同的过滤参数，保证"备份怎么来、恢复就怎么用"；
#   * 先写 .partial 再 mv，避免中途失败留下半截文件被当成有效备份；
#   * 用 `pg_restore -l` 校验可读性并数 TOC 条目，坏 dump 直接失败（退出码 1）；
#   * 保留期按文件名里的时间戳/文件 mtime 清理，只删 `liorvix-*.dump`，不动别的文件。
set -Eeuo pipefail

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
REPO_ROOT="$(cd "${SCRIPT_DIR}/../.." && pwd)"

: "${BACKUP_DB_URL:?BACKUP_DB_URL is required, e.g. postgresql://postgres@127.0.0.1:5432/postgres}"
OUT_DIR="${OUT_DIR:-/opt/liorvix-backups}"
RETENTION_DAYS="${RETENTION_DAYS:-7}"
PG_BIN="${PG_BIN:-}"
STAMP="$(date +%Y%m%d-%H%M%S)"
NAME="liorvix-${STAMP}.dump"
TMP="${OUT_DIR}/${NAME}.partial"
FINAL="${OUT_DIR}/${NAME}"
LOG="${OUT_DIR}/backup.log"

if [ -n "${PG_BIN}" ]; then
  export PATH="${PG_BIN}:${PATH}"
fi
command -v pg_dump >/dev/null 2>&1 || { echo "pg_dump not found (set PG_BIN)" >&2; exit 1; }
command -v pg_restore >/dev/null 2>&1 || { echo "pg_restore not found (set PG_BIN)" >&2; exit 1; }

umask 077
mkdir -p "${OUT_DIR}"

log() { printf '[backup %s] %s\n' "$(date +%H:%M:%S)" "$*" | tee -a "${LOG}"; }
die() { printf '[backup %s] ERROR: %s\n' "$(date +%H:%M:%S)" "$*" >&2 | tee -a "${LOG}"; exit 1; }

cleanup_partial() {
  if [ -f "${TMP}" ]; then
    rm -f "${TMP}"
    log "removed partial file after failure"
  fi
}
trap cleanup_partial EXIT

log "starting: ${FINAL}"
START=$(date +%s)

set +e
pg_dump "${BACKUP_DB_URL}" \
  --format=custom \
  --compress=6 \
  --schema=public \
  --schema=auth \
  --no-publications \
  --no-subscriptions \
  --file="${TMP}" 2>>"${LOG}"
STATUS=$?
set -e
[ "${STATUS}" -eq 0 ] || die "pg_dump failed with exit ${STATUS}"

DURATION=$(( $(date +%s) - START ))
SIZE_BYTES=$(wc -c < "${TMP}" | tr -d ' ')
[ "${SIZE_BYTES}" -gt 0 ] || die "pg_dump produced an empty file"

TOC_ENTRIES=$(pg_restore -l "${TMP}" 2>/dev/null | grep -cE '^[0-9]+;' || true)
[ "${TOC_ENTRIES}" -gt 100 ] || die "dump looks unreadable (TOC entries=${TOC_ENTRIES})"

mv -f "${TMP}" "${FINAL}"
trap - EXIT
chmod 600 "${FINAL}"

# 伴生 SQL：`--schema=` 过滤会让 pg_dump **不导出 CREATE EXTENSION**（VPS 实测 TOC 里
# 扩展条目为 0）。恢复流程本来就是"先 bootstrap 再 restore"，bootstrap 会建扩展；但为了让
# 备份包自身自洽（脱离仓库/脚本也能救回来），把必需扩展写成一份可直接 `psql -f` 的 SQL。
PRE_SQL="${FINAL%.dump}.pre.sql"
{
  echo "-- Liorvix backup prerequisites — run this BEFORE pg_restore into a brand-new database."
  echo "-- Generated by scripts/migrate/db-backup.sh; safe to re-run (IF NOT EXISTS)."
  echo "create extension if not exists pg_trgm with schema public;"
  echo "create extension if not exists pgcrypto with schema public;"
  echo "create extension if not exists \"uuid-ossp\" with schema public;"
  echo "create extension if not exists pg_stat_statements;"
  echo "create extension if not exists supabase_vault;"
} > "${PRE_SQL}.tmp"
mv -f "${PRE_SQL}.tmp" "${PRE_SQL}"
chmod 600 "${PRE_SQL}"

log "done in ${DURATION}s: $(du -h "${FINAL}" | cut -f1) (${SIZE_BYTES} bytes), TOC entries=${TOC_ENTRIES}"
log "prerequisites: $(basename "${PRE_SQL}") (extensions are not in the dump TOC by design)"

# 保留期清理（只匹配本脚本的命名，避免误删其它备份）
if [ "${RETENTION_DAYS}" -ge 1 ]; then
  DELETED=0
  while IFS= read -r old; do
    [ -n "${old}" ] || continue
    rm -f "${old}"
    DELETED=$((DELETED + 1))
    log "pruned $(basename "${old}")"
  done < <(find "${OUT_DIR}" -maxdepth 1 -name 'liorvix-*.dump' -type f -mtime +"${RETENTION_DAYS}" 2>/dev/null | grep -v "/${NAME}$" || true)
  # 伴生 .pre.sql 跟着 dump 一起过期，避免目录里堆孤儿文件
  while IFS= read -r old; do
    [ -n "${old}" ] || continue
    rm -f "${old}"
    DELETED=$((DELETED + 1))
    log "pruned $(basename "${old}")"
  done < <(find "${OUT_DIR}" -maxdepth 1 -name 'liorvix-*.pre.sql' -type f -mtime +"${RETENTION_DAYS}" 2>/dev/null | grep -v "/$(basename "${PRE_SQL}")$" || true)
  log "retention: kept last ${RETENTION_DAYS} days, pruned ${DELETED} file(s)"
fi

log "backup ok: ${FINAL}"