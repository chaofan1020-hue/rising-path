begin;

create table if not exists public.plans (
  id bigint generated by default as identity primary key,
  code text not null unique,
  name text not null,
  price_monthly numeric(10, 2) not null default 0,
  price_yearly numeric(10, 2) not null default 0,
  currency text not null default 'USD',
  entitlements jsonb not null default '{}'::jsonb,
  is_active boolean not null default true,
  sort_order integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.subscriptions (
  id bigint generated by default as identity primary key,
  user_id uuid not null unique references auth.users(id) on delete cascade,
  plan_id bigint not null references public.plans(id) on delete restrict,
  stripe_customer_id text,
  stripe_subscription_id text,
  status text not null default 'active',
  billing_interval text not null default 'monthly',
  current_period_start timestamptz,
  current_period_end timestamptz,
  cancel_at_period_end boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint subscriptions_status_check check (status in ('active', 'trialing', 'past_due', 'canceled')),
  constraint subscriptions_interval_check check (billing_interval in ('monthly', 'yearly'))
);

create table if not exists public.entitlements (
  id bigint generated by default as identity primary key,
  plan_id bigint not null references public.plans(id) on delete cascade,
  feature_code text not null,
  quota_per_month integer,
  grant_on_signup integer not null default 0,
  sort_order integer not null default 0,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint entitlements_plan_feature_unique unique (plan_id, feature_code),
  constraint entitlements_feature_check check (
    feature_code in (
      'ai_match',
      'ats_optimize',
      'mock_interview',
      'networking',
      'dashboard_advanced',
      'auto_apply'
    )
  ),
  constraint entitlements_quota_check check (
    quota_per_month is null or quota_per_month >= 0
  )
);

create table if not exists public.usage_ledger (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  feature_code text not null,
  bucket_key text not null,
  source text not null default 'monthly',
  used_count integer not null default 0,
  limit_value integer,
  period_start timestamptz,
  period_end timestamptz,
  credit_pack_id bigint,
  ai_usage_event_id bigint references public.ai_usage_events(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint usage_ledger_user_feature_bucket_unique unique (user_id, feature_code, bucket_key),
  constraint usage_ledger_source_check check (source in ('monthly', 'grant', 'credit_pack')),
  constraint usage_ledger_count_check check (used_count >= 0),
  constraint usage_ledger_limit_check check (limit_value is null or limit_value >= 0)
);

create table if not exists public.credit_packs (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  feature_code text not null,
  stripe_payment_intent_id text,
  quantity integer not null default 0,
  remaining integer not null default 0,
  status text not null default 'active',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint credit_packs_feature_check check (
    feature_code in (
      'ai_match',
      'ats_optimize',
      'mock_interview',
      'networking',
      'dashboard_advanced',
      'auto_apply'
    )
  ),
  constraint credit_packs_count_check check (
    quantity >= 0 and remaining >= 0 and remaining <= quantity
  ),
  constraint credit_packs_status_check check (status in ('active', 'consumed', 'refunded'))
);

alter table public.plans enable row level security;
alter table public.subscriptions enable row level security;
alter table public.entitlements enable row level security;
alter table public.usage_ledger enable row level security;
alter table public.credit_packs enable row level security;

drop policy if exists plans_public_select on public.plans;
create policy plans_public_select
  on public.plans
  for select to anon, authenticated
  using (true);

drop policy if exists subscriptions_owner_select on public.subscriptions;
create policy subscriptions_owner_select
  on public.subscriptions
  for select to authenticated
  using (user_id = auth.uid());

drop policy if exists entitlements_public_select on public.entitlements;
create policy entitlements_public_select
  on public.entitlements
  for select to anon, authenticated
  using (true);

drop policy if exists usage_ledger_owner_select on public.usage_ledger;
create policy usage_ledger_owner_select
  on public.usage_ledger
  for select to authenticated
  using (user_id = auth.uid());

drop policy if exists credit_packs_owner_select on public.credit_packs;
create policy credit_packs_owner_select
  on public.credit_packs
  for select to authenticated
  using (user_id = auth.uid());

revoke all on table public.plans from anon, authenticated;
grant select on table public.plans to anon, authenticated;
revoke all on table public.subscriptions from anon, authenticated;
grant select on table public.subscriptions to authenticated;
revoke all on table public.entitlements from anon, authenticated;
grant select on table public.entitlements to anon, authenticated;
revoke all on table public.usage_ledger from anon, authenticated;
grant select on table public.usage_ledger to authenticated;
revoke all on table public.credit_packs from anon, authenticated;
grant select on table public.credit_packs to authenticated;

grant usage, select on all sequences in schema public to anon, authenticated, service_role;

create index if not exists subscriptions_user_active_idx
  on public.subscriptions(user_id, status)
  where status in ('active', 'trialing');
create index if not exists entitlements_plan_active_idx
  on public.entitlements(plan_id, feature_code, is_active);
create index if not exists usage_ledger_user_bucket_idx
  on public.usage_ledger(user_id, feature_code, bucket_key);
create index if not exists credit_packs_user_active_idx
  on public.credit_packs(user_id, feature_code, status)
  where status = 'active';

