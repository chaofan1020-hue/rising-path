create or replace function public.get_ai_usage_student_summary_v4(
  p_feature text default null,
  p_provider text default null,
  p_status text default null,
  p_usage_source text default null,
  p_from timestamptz default null,
  p_to timestamptz default null,
  p_page integer default 1,
  p_page_size integer default 50
)
returns table (
  user_id uuid,
  display_name text,
  call_count bigint,
  successful_calls bigint,
  failed_calls bigint,
  input_tokens bigint,
  output_tokens bigint,
  total_tokens bigint,
  actual_calls bigint,
  estimated_calls bigint,
  unknown_calls bigint,
  audio_calls bigint,
  input_audio_seconds numeric,
  output_audio_seconds numeric,
  audio_tokens bigint,
  text_characters bigint,
  billing_units numeric,
  priced_calls bigint,
  unpriced_calls bigint,
  estimated_costs jsonb
)
language sql
stable
security definer
set search_path = public
as $$
  with filtered as materialized (
    select *
    from public.ai_usage_events events
    where events.user_id is not null
      and (p_feature is null or events.feature = p_feature)
      and (p_provider is null or events.provider = p_provider)
      and (p_status is null or events.status = p_status)
      and (p_usage_source is null or events.usage_source = p_usage_source)
      and (p_from is null or events.created_at >= p_from)
      and (p_to is null or events.created_at < p_to)
  ), cost_totals as (
    select user_id, currency, sum(estimated_cost)::numeric(18, 8) as amount
    from filtered
    where estimated_cost is not null
    group by user_id, currency
  )
  select
    events.user_id,
    coalesce(nullif(profiles.display_name, ''), '未命名用户')::text,
    count(*)::bigint,
    count(*) filter (where events.status = 'success')::bigint,
    count(*) filter (where events.status = 'error')::bigint,
    coalesce(sum(events.input_tokens), 0)::bigint,
    coalesce(sum(events.output_tokens), 0)::bigint,
    coalesce(sum(events.total_tokens), 0)::bigint,
    count(*) filter (where events.usage_source = 'actual')::bigint,
    count(*) filter (where events.usage_source = 'estimated')::bigint,
    count(*) filter (where events.usage_source = 'unknown')::bigint,
    count(*) filter (where events.modality = 'audio')::bigint,
    coalesce(sum(events.input_audio_seconds), 0),
    coalesce(sum(events.output_audio_seconds), 0),
    coalesce(sum(events.audio_tokens), 0)::bigint,
    coalesce(sum(events.text_characters), 0)::bigint,
    coalesce(sum(events.billing_units), 0),
    count(*) filter (where events.estimated_cost is not null)::bigint,
    count(*) filter (where events.estimated_cost is null)::bigint,
    coalesce((
      select jsonb_object_agg(currency, amount)
      from cost_totals
      where cost_totals.user_id = events.user_id
    ), '{}'::jsonb)
  from filtered events
  left join public.profiles profiles on profiles.id = events.user_id
  group by events.user_id, profiles.display_name
  order by coalesce(sum(events.estimated_cost), 0) desc, coalesce(sum(events.total_tokens), 0) desc, events.user_id
  offset greatest(p_page - 1, 0) * least(greatest(p_page_size, 1), 100)
  limit least(greatest(p_page_size, 1), 100);
$$;

revoke all on function public.get_ai_usage_summary_v3(uuid, text, text, text, text, timestamptz, timestamptz) from public;
revoke all on function public.get_ai_usage_feature_summary_v3(uuid, text, text, text, text, timestamptz, timestamptz) from public;
revoke all on function public.get_ai_usage_student_summary_v4(text, text, text, text, timestamptz, timestamptz, integer, integer) from public;
grant execute on function public.get_ai_usage_summary_v3(uuid, text, text, text, text, timestamptz, timestamptz) to service_role;
grant execute on function public.get_ai_usage_feature_summary_v3(uuid, text, text, text, text, timestamptz, timestamptz) to service_role;
