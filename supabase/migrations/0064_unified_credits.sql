create table if not exists public.credit_accounts (
  id bigint generated by default as identity primary key,
  user_id uuid not null unique references auth.users(id) on delete cascade,
  balance numeric(18, 4) not null default 0,
  lifetime_granted numeric(18, 4) not null default 0,
  lifetime_spent numeric(18, 4) not null default 0,
  version integer not null default 1,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint credit_accounts_balance_check check (balance >= 0),
  constraint credit_accounts_granted_check check (lifetime_granted >= 0),
  constraint credit_accounts_spent_check check (lifetime_spent >= 0)
);

create table if not exists public.credit_price_rules (
  id bigint generated by default as identity primary key,
  metric text not null unique,
  display_name text not null,
  unit_name text not null default '次',
  credit_cost numeric(18, 4) not null,
  enabled boolean not null default true,
  max_units_per_request numeric(18, 4),
  notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint credit_price_rules_cost_check check (credit_cost > 0),
  constraint credit_price_rules_max_check check (max_units_per_request is null or max_units_per_request > 0)
);

create table if not exists public.credit_reservations (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  account_id bigint not null references public.credit_accounts(id) on delete cascade,
  metric text not null references public.credit_price_rules(metric),
  units numeric(18, 4) not null,
  credits numeric(18, 4) not null,
  idempotency_key text not null,
  status text not null default 'reserved',
  expires_at timestamptz not null default (now() + interval '10 minutes'),
  created_at timestamptz not null default now(),
  settled_at timestamptz,
  metadata jsonb not null default '{}'::jsonb,
  constraint credit_reservations_units_check check (units > 0),
  constraint credit_reservations_credits_check check (credits > 0),
  constraint credit_reservations_status_check check (status in ('reserved', 'committed', 'released', 'expired')),
  unique (user_id, idempotency_key)
);

create table if not exists public.credit_ledger (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  account_id bigint not null references public.credit_accounts(id) on delete cascade,
  reservation_id bigint references public.credit_reservations(id) on delete set null,
  entry_type text not null,
  delta numeric(18, 4) not null,
  balance_after numeric(18, 4) not null,
  metric text,
  idempotency_key text,
  reason text,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  constraint credit_ledger_entry_type_check check (entry_type in ('grant', 'purchase', 'reserve', 'refund', 'adjustment')),
  constraint credit_ledger_balance_check check (balance_after >= 0),
  unique (user_id, idempotency_key)
);

create index if not exists credit_reservations_user_status_idx
  on public.credit_reservations(user_id, status, created_at desc);
create index if not exists credit_reservations_expiry_idx
  on public.credit_reservations(status, expires_at)
  where status = 'reserved';
create index if not exists credit_ledger_user_created_idx
  on public.credit_ledger(user_id, created_at desc);

