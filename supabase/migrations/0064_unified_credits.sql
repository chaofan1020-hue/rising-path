create or replace function public.reserve_credits(
  p_user_id uuid,
  p_metric text,
  p_units numeric default 1,
  p_idempotency_key text default null,
  p_require_beta boolean default false,
  p_metadata jsonb default '{}'::jsonb
)
returns table (
  allowed boolean,
  code text,
  reservation_id bigint,
  credits numeric,
  remaining numeric
)
language plpgsql
security definer
set search_path = public
as $$
declare
  account public.credit_accounts%rowtype;
  rule public.credit_price_rules%rowtype;
  reservation public.credit_reservations%rowtype;
  key_value text := nullif(trim(coalesce(p_idempotency_key, '')), '');
  charge numeric;
begin
  if p_user_id is null or p_units is null or p_units <= 0 or trim(coalesce(p_metric, '')) = '' then
    return query select false, 'INVALID_CREDIT_REQUEST', null::bigint, 0::numeric, 0::numeric;
    return;
  end if;

  if key_value is not null then
    select * into reservation
      from public.credit_reservations
     where user_id = p_user_id and idempotency_key = key_value;
    if reservation.id is not null and reservation.status in ('reserved', 'committed') then
      select * into account from public.credit_accounts where id = reservation.account_id;
      return query select true, 'IDEMPOTENT_REPLAY', reservation.id, reservation.credits, coalesce(account.balance, 0);
      return;
    end if;
    if reservation.id is not null then
      return query select false, 'IDEMPOTENCY_REPLAY', reservation.id, reservation.credits, 0::numeric;
      return;
    end if;
  end if;

  if p_require_beta then
    if not exists (
      select 1 from public.beta_entitlements e
       where e.user_id = p_user_id
         and e.status = 'active'
         and now() >= e.period_start
         and now() < e.period_end
    ) then
      if exists (select 1 from public.beta_entitlements where user_id = p_user_id) then
        return query select false, 'BETA_ACCESS_INACTIVE', null::bigint, 0::numeric, 0::numeric;
      end if;
      return query select false, 'BETA_ACCESS_REQUIRED', null::bigint, 0::numeric, 0::numeric;
      return;
    end if;
  end if;

  select * into rule from public.credit_price_rules
   where metric = trim(p_metric) and enabled = true;
  if rule.id is null then
    return query select false, 'CREDIT_METRIC_NOT_CONFIGURED', null::bigint, 0::numeric, 0::numeric;
    return;
  end if;
  if rule.max_units_per_request is not null and p_units > rule.max_units_per_request then
    return query select false, 'CREDIT_REQUEST_TOO_LARGE', null::bigint, 0::numeric, 0::numeric;
    return;
  end if;
  charge := rule.credit_cost * p_units;

  insert into public.credit_accounts (user_id) values (p_user_id)
    on conflict (user_id) do nothing;
  select * into account from public.credit_accounts where user_id = p_user_id for update;

  for reservation in
    select * from public.credit_reservations
     where user_id = p_user_id and status = 'reserved' and expires_at <= now()
     for update
  loop
    update public.credit_accounts
       set balance = balance + reservation.credits,
           lifetime_spent = greatest(0, lifetime_spent - reservation.credits),
           version = version + 1,
           updated_at = now()
     where id = reservation.account_id;
    insert into public.credit_ledger (user_id, account_id, reservation_id, entry_type, delta, balance_after, metric, idempotency_key, reason, metadata)
    select reservation.user_id, a.id, reservation.id, 'refund', reservation.credits, a.balance, reservation.metric,
           'refund:' || reservation.id::text, '过期预扣自动退回积分', reservation.metadata
      from public.credit_accounts a where a.id = reservation.account_id;
    update public.credit_reservations set status = 'expired', settled_at = now() where id = reservation.id;
  end loop;
  select * into account from public.credit_accounts where id = account.id for update;

  if account.balance < charge then
    return query select false, 'CREDIT_INSUFFICIENT', null::bigint, charge, account.balance;
    return;
  end if;

  update public.credit_accounts
     set balance = balance - charge,
         lifetime_spent = lifetime_spent + charge,
         version = version + 1,
         updated_at = now()
   where id = account.id;

  insert into public.credit_reservations (user_id, account_id, metric, units, credits, idempotency_key, metadata)
  values (p_user_id, account.id, trim(p_metric), p_units, charge,
          coalesce(key_value, md5(random()::text || clock_timestamp()::text || p_user_id::text)),
          coalesce(p_metadata, '{}'::jsonb))
  returning * into reservation;

  insert into public.credit_ledger (user_id, account_id, reservation_id, entry_type, delta, balance_after, metric, idempotency_key, reason, metadata)
  values (p_user_id, account.id, reservation.id, 'reserve', -charge, account.balance - charge, trim(p_metric),
          'reservation:' || reservation.id::text, '预扣积分', coalesce(p_metadata, '{}'::jsonb));

  return query select true, 'RESERVED', reservation.id, charge, account.balance - charge;
exception when unique_violation then
  select * into reservation from public.credit_reservations where user_id = p_user_id and idempotency_key = key_value;
  if reservation.id is not null and reservation.status in ('reserved', 'committed') then
    return query select true, 'IDEMPOTENT_REPLAY', reservation.id, reservation.credits, 0::numeric;
  end if;
  raise;
end;
$$;

create or replace function public.settle_credits(
  p_reservation_id bigint,
  p_status text
)
returns boolean
language plpgsql
security definer
set search_path = public
as $$
declare
  reservation public.credit_reservations%rowtype;
  account public.credit_accounts%rowtype;
begin
  if p_status not in ('committed', 'released') then return false; end if;
  select * into reservation from public.credit_reservations where id = p_reservation_id for update;
  if reservation.id is null or reservation.status <> 'reserved' then return false; end if;
  if p_status = 'committed' then
    update public.credit_reservations set status = 'committed', settled_at = now() where id = reservation.id;
    return true;
  end if;

  select * into account from public.credit_accounts where id = reservation.account_id for update;
  update public.credit_accounts
     set balance = balance + reservation.credits,
         lifetime_spent = greatest(0, lifetime_spent - reservation.credits),
         version = version + 1,
         updated_at = now()
   where id = account.id;
  insert into public.credit_ledger (user_id, account_id, reservation_id, entry_type, delta, balance_after, metric, idempotency_key, reason, metadata)
  values (reservation.user_id, account.id, reservation.id, 'refund', reservation.credits, account.balance + reservation.credits,
          reservation.metric, 'refund:' || reservation.id::text, 'AI 调用失败退回积分', reservation.metadata);
  update public.credit_reservations set status = 'released', settled_at = now() where id = reservation.id;
  return true;
end;
$$;

create or replace function public.grant_credits(
  p_user_id uuid,
  p_amount numeric,
  p_entry_type text default 'grant',
  p_idempotency_key text default null,
  p_reason text default null,
  p_metadata jsonb default '{}'::jsonb
)
returns table (account_id bigint, balance numeric, ledger_id bigint)
language plpgsql
security definer
set search_path = public
as $$
declare
  account public.credit_accounts%rowtype;
  v_ledger_id bigint;
  key_value text := nullif(trim(coalesce(p_idempotency_key, '')), '');
begin
  if p_user_id is null or p_amount = 0 or p_entry_type not in ('grant', 'purchase', 'adjustment') then
    raise exception 'invalid credit grant';
  end if;
  if key_value is not null and exists (select 1 from public.credit_ledger where user_id = p_user_id and idempotency_key = key_value) then
    select a.* into account from public.credit_accounts a where a.user_id = p_user_id;
    select l.id into v_ledger_id from public.credit_ledger l where l.user_id = p_user_id and l.idempotency_key = key_value;
    return query select account.id, account.balance, v_ledger_id;
    return;
  end if;
  insert into public.credit_accounts (user_id) values (p_user_id) on conflict (user_id) do nothing;
  select * into account from public.credit_accounts where user_id = p_user_id for update;
  if account.balance + p_amount < 0 then raise exception 'credit balance cannot be negative'; end if;
  update public.credit_accounts as credit_account
     set balance = credit_account.balance + p_amount,
         lifetime_granted = credit_account.lifetime_granted + case when p_amount > 0 then p_amount else 0 end,
         version = credit_account.version + 1,
         updated_at = now()
   where id = account.id
   returning * into account;
  insert into public.credit_ledger (user_id, account_id, entry_type, delta, balance_after, idempotency_key, reason, metadata)
  values (p_user_id, account.id, p_entry_type, p_amount, account.balance, key_value, p_reason, coalesce(p_metadata, '{}'::jsonb))
  returning id into v_ledger_id;
  return query select account.id, account.balance, v_ledger_id;
end;
$$;

