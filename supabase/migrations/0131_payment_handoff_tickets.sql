begin;

create table if not exists public.payment_handoff_tickets (
  id bigint generated by default as identity primary key,
  token_hash text not null unique,
  order_id bigint not null references public.billing_orders(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  expires_at timestamptz not null,
  redeemed_at timestamptz,
  created_at timestamptz not null default now()
);

create index if not exists payment_handoff_tickets_expiry_idx
  on public.payment_handoff_tickets(expires_at);
alter table public.payment_handoff_tickets enable row level security;
revoke all on public.payment_handoff_tickets from anon, authenticated;
grant select, insert, update, delete on public.payment_handoff_tickets to service_role;
grant usage, select on sequence public.payment_handoff_tickets_id_seq to service_role;

commit;
